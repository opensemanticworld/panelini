import csv
from pathlib import Path

HERE = Path(__file__).parent

with (HERE / "runs.csv").open() as f:
    rows = list(csv.DictReader(f))


def avg(phase, directory, exclude_fail=True):
    vals = [
        float(r["duration_s"])
        for r in rows
        if r["phase"] == phase
        and r["directory"] == directory
        and (not exclude_fail or (r["failed"] == "0" and r["errors"] == "0"))
    ]
    return sum(vals) / len(vals)


# "Before" values come from runs.csv's "baseline" phase. wunderbaum's is a
# real measured control run (git-stash, 2 runs); the other four are
# estimates read from the pre-conversion time.sleep() calls in each file
# (no separate baseline run was captured for those - see the notes column
# in runs.csv), but they still live in runs.csv, not hardcoded here.
DIRECTORIES = ["wunderbaum", "visnetwork", "jsoneditor", "terminalmirror", "usecases"]

# "After" phase/directory pair per directory in runs.csv (naming isn't
# uniform - wunderbaum's clean post-fix runs are under a distinct phase).
AFTER_RUNS = {
    "wunderbaum": ("wunderbaum", "full-dir-fixed"),
    "visnetwork": ("visnetwork", "full-dir"),
    "jsoneditor": ("jsoneditor", "full-dir"),
    "terminalmirror": ("terminalmirror", "full-dir"),
    "usecases": ("usecases", "full-dir"),
}

MARKDOWN_TEMPLATE = """\
# UI Test Suite Speed-Up: Charts

Generated by `chartgen.py` from `runs.csv` in this same folder - re-run
that script to regenerate this file after `runs.csv` changes.

Mermaid `xychart-beta` diagram - renders natively in GitHub, GitLab, and
VS Code's markdown preview, no image asset or build step required
(Mermaid v10.7+ for `xychart-beta` support).

## Per-directory duration: before vs after (+ total)

"After" values are real averages of the clean repeated runs recorded in
`runs.csv` (excludes any run with a failure/error). "Before" values come
from `runs.csv`'s `baseline` phase: `wunderbaum`'s is a real measured
control run (`git stash`); the other four are estimates read directly
from the pre-conversion `time.sleep()` calls in each file (see the
`notes` column in `runs.csv` - no separate baseline run was captured for
those three). "Total" sums the 5 directories (each run standalone, so
per-directory Playwright/browser startup is counted once per bar - it is
not the same number as a full-suite run, which amortizes that cost once
overall and also includes untouched AI/unit tests).

```mermaid
%%{{init: {{"themeVariables": {{"xyChart": {{"plotColorPalette": "#2a78d6, #eb6834"}}}}}}}}%%
xychart-beta
    title "Per-directory duration: before vs after (seconds)"
    x-axis [{x_axis}]
    y-axis "Duration (s)" 0 --> {y_max}
    bar [{before_bar}]
    bar [{after_bar}]
```

| directory | before (s) | after (s) | speedup |
| --- | --- | --- | --- |
{table_rows}

## Regenerating

```bash
python3 chartgen.py
```
"""


def render_markdown(results, totals):
    x_axis = ", ".join(f'"{name}"' for name, *_ in results) + ', "Total"'
    before_bar = ", ".join(f"{b:.0f}" for _, b, _, _ in results) + f", {totals[0]:.0f}"
    after_bar = ", ".join(f"{a:.0f}" for _, _, a, _ in results) + f", {totals[1]:.0f}"
    y_max = round((totals[0] + 50) / 50) * 50

    table_rows = "\n".join(
        f"| {name} | {before:.2f} | {after:.2f} | {before / after:.2f}x |" for name, before, after, _ in results
    )
    table_rows += f"\n| **Total** | **{totals[0]:.2f}** | **{totals[1]:.2f}** | **{totals[0] / totals[1]:.2f}x** |"

    return MARKDOWN_TEMPLATE.format(
        x_axis=x_axis,
        y_max=y_max,
        before_bar=before_bar,
        after_bar=after_bar,
        table_rows=table_rows,
    )


if __name__ == "__main__":
    results = []
    for name in DIRECTORIES:
        before_value = avg("baseline", name)
        after_phase, after_directory = AFTER_RUNS[name]
        after_value = avg(after_phase, after_directory)
        results.append((name, before_value, after_value, before_value / after_value))
        print(f"{name:15s} {before_value:7.2f}s {after_value:7.2f}s {before_value / after_value:7.2f}x")

    before_total = sum(b for _, b, _, _ in results)
    after_total = sum(a for _, _, a, _ in results)
    print(f"{'Total':15s} {before_total:7.2f}s {after_total:7.2f}s {before_total / after_total:7.2f}x")

    markdown = render_markdown(results, (before_total, after_total))
    (HERE / "CHARTS.md").write_text(markdown)
    print("\nWrote CHARTS.md")
